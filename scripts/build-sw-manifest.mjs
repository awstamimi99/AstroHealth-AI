// scripts/build-sw-manifest.mjs
// DEV-TIME ONLY. Walks the repo and writes js/core/precache-manifest.js — the
// list of every runtime file the service worker (sw.js) must cache so the
// whole app works with no network.
//
// Re-run (`npm run build:sw`) whenever you ADD, RENAME or DELETE a runtime
// file, and commit the result. Remember to bump APP_VERSION / CACHE_VERSION
// when you ship changes so users get the new files.

import { readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "js/core/precache-manifest.js");

// Top-level folders/files that are NOT part of the running app.
const EXCLUDE_DIRS = new Set([
  "node_modules", "scripts", "tests", "docs", "server", "videos", ".git", ".github", ".vscode", ".claude",
]);
const EXCLUDE_FILES = new Set([
  "package.json", "package-lock.json", ".gitignore", ".DS_Store", "sw.js",
  "README.md", "CONTRIBUTING.md", "LICENSE",
]);
// File types we never need offline. Video guides (assets/guides/*.mp4, tens of MB) are
// streamed on demand instead of being downloaded on every install.
const EXCLUDE_EXT = [".md", ".map", ".gitkeep", ".log", ".mp4", ".webm", ".mov"];
// Licence files are kept in the repo but are not needed at runtime.
const EXCLUDE_NAMES = new Set(["LICENSE", "LICENSE.md", ".gitkeep"]);

function walk(dir, list = []) {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    const rel = relative(ROOT, full).split(sep).join("/");
    const top = rel.split("/")[0];
    if (EXCLUDE_DIRS.has(top) || EXCLUDE_NAMES.has(name) || name.startsWith(".")) continue;
    if (statSync(full).isDirectory()) {
      walk(full, list);
    } else {
      if (!rel.includes("/") && EXCLUDE_FILES.has(name)) continue;
      if (EXCLUDE_EXT.some((ext) => name.endsWith(ext))) continue;
      list.push(rel);
    }
  }
  return list;
}

const files = walk(ROOT);
// "./" makes the service worker cache the bare folder URL (e.g. "/") too.
const urls = ["./", ...files.map((f) => `./${f}`)];

const body =
  `// GENERATED by scripts/build-sw-manifest.mjs — do not edit by hand.\n` +
  `// Every runtime file the service worker precaches. Run "npm run build:sw"\n` +
  `// after adding, renaming or deleting files.\n` +
  `// Loaded by sw.js with importScripts(), so it sets a global (no "export").\n\n` +
  `self.PRECACHE_URLS = ${JSON.stringify(urls, null, 2)};\n`;

writeFileSync(OUT, body);
console.log(`✓ ${urls.length} files → js/core/precache-manifest.js`);
