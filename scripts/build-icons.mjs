// scripts/build-icons.mjs
// DEV-TIME ONLY. Reads a CURATED list of Lucide icons from
// node_modules/lucide-static/icons/<name>.svg and writes vendor/lucide/icons.js:
//
//   export const ICONS = { "activity": "<path d=\"…\"/>", … };
//
// Only the INNER markup of each <svg> is kept; js/components/icon.js wraps it
// in an <svg viewBox="0 0 24 24"> at runtime.
//
// Need a new icon? Add its name to the list below, run `npm run setup`,
// and commit the regenerated vendor/lucide/icons.js.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "node_modules/lucide-static/icons");
const OUT = join(ROOT, "vendor/lucide/icons.js");

export const ICON_NAMES = [
  "activity", "heart", "droplet", "moon", "zap", "smile", "frown", "meh",
  "brain", "gauge", "bell", "layout-dashboard", "users", "user",
  "triangle-alert", "circle-alert", "circle-check", "info", "clock", "history",
  "file-text", "sliders-horizontal", "settings", "wifi", "wifi-off", "log-out",
  "play", "pause", "square", "rotate-ccw", "shield", "cpu", "eye", "eye-off",
  "lock", "send", "check", "x", "flask-conical", "rocket", "database",
  "message-circle", "filter", "chevron-right", "chevron-down", "search",
  "battery", "download", "upload", "globe", "arrow-right", "book-open", "radio",
  "menu", "trash-2", "plus", "calendar", "printer",
];

const icons = {};
for (const name of ICON_NAMES) {
  const file = join(SRC, `${name}.svg`);
  if (!existsSync(file)) {
    console.error(`✗ Lucide icon "${name}" not found — check the name on lucide.dev`);
    process.exit(1);
  }
  const svg = readFileSync(file, "utf8");
  // Grab everything between <svg …> and </svg>, then collapse whitespace.
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>[\s\S]*$/, "")
    .replace(/\s*\n\s*/g, "")
    .replace(/\s+\/>/g, "/>")
    .trim();
  icons[name] = inner;
}

const version = JSON.parse(
  readFileSync(join(ROOT, "node_modules/lucide-static/package.json"), "utf8")
).version;

const body =
  `// GENERATED by scripts/build-icons.mjs — do not edit by hand.\n` +
  `// Lucide icons v${version} (ISC licence, see vendor/lucide/LICENSE).\n` +
  `// Each value is the inner markup of a 24×24 stroke icon.\n\n` +
  `export const ICONS = ${JSON.stringify(icons, null, 2)};\n\n` +
  `export const ICON_NAMES = Object.keys(ICONS);\n`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);
console.log(`✓ wrote ${ICON_NAMES.length} icons → vendor/lucide/icons.js`);
